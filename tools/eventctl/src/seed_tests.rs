//! Live-Postgres tests for `eventctl seed-mockup` (house `test_pool()` pattern, like
//! `core/asyncevents/src/admin_tests.rs`). `seed_mockup` picks the busiest stream over the
//! WHOLE shared event log and the test role cannot `CREATE DATABASE`, so each test makes
//! its own stream the busiest by construction ([`busiest_floor`]: strictly more events
//! than any stream already in the log) instead of assuming an empty cluster. The two seed
//! subscription ids are fixed, so the tests serialize on [`LOCK`] and clear the ids and
//! their own events before and after.

use crate::seed::{seed_mockup, seed_mockup_on, LAGGING_ID, PAUSED_ID};
use asyncevents::admin;
use sqlx::{PgPool, Row as _};
use std::future::Future;

/// Prefix of every topic these tests append to; the cleanup keys on it.
const TOPIC_PREFIX: &str = "eventctl.seedtest.";

/// The seed ids are global, so two of these tests must never overlap.
static LOCK: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

/// The row columns the seed owns, read back as the designed-state assertion surface.
#[derive(Debug, PartialEq)]
struct Row {
    topic: String,
    version: i32,
    state: String,
    failures: i32,
    last_error: Option<String>,
    cursor: (i64, String, i64),
    next_attempt_is_null: bool,
    spec_hash: String,
    start_kind: String,
}

async fn row(pool: &PgPool, id: &str) -> Row {
    let r = sqlx::query(
        "SELECT topic, contract_version, state, consecutive_failures, last_error,                 cursor_generation, cursor_xid::text AS cursor_xid, cursor_tie,                 next_attempt_at IS NULL AS next_attempt_is_null, spec_hash, start_kind          FROM asyncevents.subscriptions WHERE subscription_id = $1",
    )
    .bind(id)
    .fetch_one(pool)
    .await
    .unwrap();
    Row {
        topic: r.get("topic"),
        version: r.get("contract_version"),
        state: r.get("state"),
        failures: r.get("consecutive_failures"),
        last_error: r.get("last_error"),
        cursor: (r.get("cursor_generation"), r.get("cursor_xid"), r.get("cursor_tie")),
        next_attempt_is_null: r.get("next_attempt_is_null"),
        spec_hash: r.get("spec_hash"),
        start_kind: r.get("start_kind"),
    }
}

async fn clear(pool: &PgPool) {
    sqlx::query("DELETE FROM asyncevents.subscriptions WHERE subscription_id = ANY($1)")
        .bind([PAUSED_ID, LAGGING_ID].map(String::from).to_vec())
        .execute(pool)
        .await
        .unwrap();
    sqlx::query("DELETE FROM asyncevents.events WHERE topic LIKE $1")
        .bind(format!("{TOPIC_PREFIX}%"))
        .execute(pool)
        .await
        .unwrap();
}

/// Runs `body` with the plane migrated and the seed ids + test events cleared, holding
/// [`LOCK`]; clears again afterwards even when `body` panics. Returns without running
/// only when `testdb` is explicitly allowed to skip.
async fn with_plane<F, Fut>(body: F)
where
    F: FnOnce(PgPool) -> Fut,
    Fut: Future<Output = ()> + Send + 'static,
{
    let _serial = LOCK.lock().await;
    let Some(pool) = testdb::test_pool().await else {
        return;
    };
    asyncevents::Plane::new(pool.clone(), testdb::dsn())
        .unwrap()
        .migrate()
        .await
        .expect("migrate the asyncevents plane");
    clear(&pool).await;
    let outcome = tokio::spawn(body(pool.clone())).await;
    clear(&pool).await;
    outcome.unwrap();
}

fn topic(name: &str) -> String {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    format!("{TOPIC_PREFIX}{name}.{}-{nanos}", std::process::id())
}

/// Appends `n` frontier-eligible events (`generation = 0` is below the seeded
/// `plane_meta.generation`) on `(topic, version)`, payload `{"n": i}`, ascending
/// `producer_xid` so `n = 0` sorts first. `tie_breaker` is generated by the table.
async fn events(pool: &PgPool, topic: &str, version: i32, n: i64) {
    sqlx::query(
        "INSERT INTO asyncevents.events \
           (generation, producer_xid, topic, contract_version, payload) \
         SELECT 0, (100 + g)::text::xid8, $1, $2, jsonb_build_object('n', g) \
         FROM generate_series(0, $3::int - 1) AS g",
    )
    .bind(topic)
    .bind(version)
    .bind(n)
    .execute(pool)
    .await
    .unwrap();
}

/// The event count of the busiest `(topic, version)` stream already in the log, so a test
/// can append strictly more than that to one stream and know it wins.
async fn busiest_floor(pool: &PgPool) -> i64 {
    sqlx::query_scalar(
        "SELECT COALESCE(max(c), 0)::bigint FROM \
           (SELECT count(*) AS c FROM asyncevents.events GROUP BY topic, contract_version) s",
    )
    .fetch_one(pool)
    .await
    .unwrap()
}

/// Branch: the `rows` table + UPSERT bind order, and the paused row's mid-stream cursor.
/// Any swapped state / failures / error constant, a leftover `next_attempt_at`, or a wrong
/// `spec_hash`/`start_kind` fails the exact-row comparison. The paused cursor must equal
/// the position of the event at index `n / 2 - 1` (read here straight from the log in the
/// plane's `(generation, producer_xid, tie_breaker)` order), so a regression to the
/// genesis cursor fails the cursor comparison, the poison read (`payload["n"] == n / 2`,
/// not the first event, 0) and the lag ordering (paused lag `n - n / 2` strictly below the
/// lagging row's `n`). The lagging row must stay at genesis with lag `n`. Removing the
/// `events < 2` guard is covered by the one-event refusal test.
#[tokio::test]
async fn seeds_both_rows_with_the_designed_state_and_the_paused_row_mid_stream() {
    with_plane(|pool| async move {
        let t = topic("designed");
        let n = busiest_floor(&pool).await + 2;
        events(&pool, &t, 1, n).await;
        let seeded = seed_mockup(&pool).await.unwrap();
        assert_eq!((seeded.topic.as_str(), seeded.version, seeded.events), (t.as_str(), 1, n));

        // The event just before the middle one (0-based index `n / 2 - 1`).
        let before_mid: (i64, String, i64) = sqlx::query_as(
            "SELECT generation, producer_xid::text AS producer_xid_text, tie_breaker \
             FROM asyncevents.events WHERE topic = $1 AND contract_version = 1 \
             ORDER BY generation, producer_xid, tie_breaker OFFSET $2 LIMIT 1",
        )
        .bind(&t)
        .bind(n / 2 - 1)
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_ne!(before_mid.1, "0", "a real event position, not genesis");

        let designed = |state: &str, failures: i32, error: &str, cursor: (i64, String, i64)| Row {
            topic: t.clone(),
            version: 1,
            state: state.into(),
            failures,
            last_error: Some(error.into()),
            cursor,
            next_attempt_is_null: true,
            spec_hash: format!("{t}|v1|genesis"),
            start_kind: "genesis".into(),
        };
        assert_eq!(
            row(&pool, PAUSED_ID).await,
            designed(
                "paused",
                5,
                r#"decode: unknown currency code "TOK2" at $.amount.currency"#,
                before_mid
            )
        );
        assert_eq!(
            row(&pool, LAGGING_ID).await,
            designed("active", 3, "wallet-svc is unavailable", (0, "0".into(), 0))
        );

        let poison = admin::poison_event(&pool, PAUSED_ID)
            .await
            .unwrap()
            .expect("the paused row has a next event");
        assert_eq!(poison.topic, t);
        assert_eq!(poison.payload["n"].as_i64(), Some(n / 2), "the stream's MIDDLE event");

        let infos = admin::info(&pool).await.unwrap();
        let lag = |id: &str| infos.iter().find(|i| i.id == id).expect("seeded row listed").lag_events;
        let (paused_lag, lagging_lag) = (lag(PAUSED_ID), lag(LAGGING_ID));
        assert_eq!((paused_lag, lagging_lag), (n - n / 2, n));
        assert!(paused_lag < lagging_lag, "the Max lag tile must name the lagging row");
    })
    .await;
}

/// Branch: `GROUP BY topic, contract_version ORDER BY count(*) DESC`. `t` v1 and v2 each
/// hold `k` events (2k in total), `u` v1 holds `k + 1`, the busiest single stream. A
/// topic-only grouping picks `t`, an ascending order picks the lone stream, and a
/// version-blind lag/poison would count `t`'s other version.
#[tokio::test]
async fn the_busiest_topic_version_stream_is_chosen() {
    with_plane(|pool| async move {
        let (lone, split, busy) = (topic("lone"), topic("split"), topic("busy"));
        let k = busiest_floor(&pool).await + 2;
        events(&pool, &lone, 1, 1).await;
        events(&pool, &split, 1, k).await;
        events(&pool, &split, 2, k).await;
        events(&pool, &busy, 1, k + 1).await;
        let seeded = seed_mockup(&pool).await.unwrap();
        assert_eq!(
            (seeded.topic.as_str(), seeded.version, seeded.events),
            (busy.as_str(), 1, k + 1)
        );
        for id in [PAUSED_ID, LAGGING_ID] {
            let r = row(&pool, id).await;
            assert_eq!((r.topic.as_str(), r.version), (busy.as_str(), 1), "{id}");
        }
    })
    .await;
}

/// Branch: the contract version is chosen WITH the topic and bound onto the rows. The
/// busiest stream is version 2, so a seed that hard-codes (or drops) the version writes 1
/// and the rows no longer read the stream they were chosen from.
#[tokio::test]
async fn the_chosen_contract_version_is_carried_onto_the_rows() {
    with_plane(|pool| async move {
        let t = topic("versions");
        let n = busiest_floor(&pool).await + 2;
        events(&pool, &t, 1, 1).await;
        events(&pool, &t, 2, n).await;
        let seeded = seed_mockup(&pool).await.unwrap();
        assert_eq!((seeded.topic.as_str(), seeded.version, seeded.events), (t.as_str(), 2, n));
        for id in [PAUSED_ID, LAGGING_ID] {
            let r = row(&pool, id).await;
            assert_eq!(r.version, 2, "{id}");
            assert_eq!(r.spec_hash, format!("{t}|v2|genesis"), "{id}");
        }
        let poison = admin::poison_event(&pool, PAUSED_ID).await.unwrap().unwrap();
        assert_eq!(poison.version, 2);
    })
    .await;
}

/// Branch: `ON CONFLICT (subscription_id) DO UPDATE SET ...` covering every column. Each
/// verb first moves part of the row away from the design (state; cursor, failures and
/// error; `retired`), asserted so the verb is known to have bitten; the re-run must put
/// the whole row back. Dropping `state`, `cursor_*`, `consecutive_failures` or
/// `last_error` from the DO UPDATE list leaves the moved value and fails.
#[tokio::test]
async fn a_rerun_resets_rows_that_were_resumed_skipped_or_retired() {
    with_plane(|pool| async move {
        let t = topic("reset");
        events(&pool, &t, 1, busiest_floor(&pool).await + 2).await;
        seed_mockup(&pool).await.unwrap();
        let designed_paused = row(&pool, PAUSED_ID).await;
        let designed_lagging = row(&pool, LAGGING_ID).await;

        // resumed: state flips to active.
        admin::resume(&pool, PAUSED_ID).await.unwrap();
        assert_eq!(row(&pool, PAUSED_ID).await.state, "active");
        // skipped: cursor advances past the first event, error becomes the reason.
        admin::skip(&pool, LAGGING_ID, "operator skip", None).await.unwrap();
        let skipped = row(&pool, LAGGING_ID).await;
        assert_ne!(skipped.cursor, designed_lagging.cursor);
        assert_eq!(skipped.failures, 0);
        assert!(
            skipped.last_error.as_deref().is_some_and(|e| e.ends_with("operator skip")),
            "{skipped:?}"
        );

        seed_mockup(&pool).await.unwrap();
        assert_eq!(row(&pool, PAUSED_ID).await, designed_paused);
        assert_eq!(row(&pool, LAGGING_ID).await, designed_lagging);

        // retired: permanent for the verbs, but the seed revives it.
        admin::retire(&pool, PAUSED_ID).await.unwrap();
        admin::retire(&pool, LAGGING_ID).await.unwrap();
        assert_eq!(row(&pool, PAUSED_ID).await.state, "retired");
        assert_eq!(row(&pool, LAGGING_ID).await.state, "retired");

        seed_mockup(&pool).await.unwrap();
        assert_eq!(row(&pool, PAUSED_ID).await, designed_paused);
        assert_eq!(row(&pool, LAGGING_ID).await, designed_lagging);
        let rows: i64 = sqlx::query_scalar(
            "SELECT count(*) FROM asyncevents.subscriptions WHERE subscription_id = ANY($1)",
        )
        .bind([PAUSED_ID, LAGGING_ID].map(String::from).to_vec())
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(rows, 2, "a re-run upserts, never duplicates");
    })
    .await;
}

/// How many of the two seed rows exist on `conn`.
async fn seed_rows(conn: &mut sqlx::PgConnection) -> i64 {
    sqlx::query_scalar(
        "SELECT count(*) FROM asyncevents.subscriptions WHERE subscription_id = ANY($1)",
    )
    .bind([PAUSED_ID, LAGGING_ID].map(String::from).to_vec())
    .fetch_one(conn)
    .await
    .unwrap()
}

/// Branch: the `let Some(..) = busiest else { bail!(..) }` empty-log refusal and the
/// `events < 2` refusal. The log is emptied inside a transaction that is rolled back
/// (`asyncevents.events` has no foreign keys and only an AFTER INSERT trigger, so the
/// DELETE is never blocked and the shared log is untouched). Removing the empty-log
/// `bail!` leaves no way to produce a `Seeded` from zero rows, so the exact error could
/// not be returned; removing the `events < 2` guard sends the one-event case into the
/// cursor lookup (`OFFSET -1` errors with a different message), so the exact-text
/// assertion fails. The "no seed row" assertions fail if rows were upserted anyway. The
/// two-event clean twin (same transaction shape) must succeed, so each refusal comes from
/// the log size alone, not from the transaction or the connection.
#[tokio::test]
async fn an_empty_or_one_event_log_is_refused_and_writes_no_rows() {
    with_plane(|pool| async move {
        let mut tx = pool.begin().await.unwrap();
        sqlx::query("DELETE FROM asyncevents.events").execute(&mut *tx).await.unwrap();
        let left: i64 = sqlx::query_scalar("SELECT count(*) FROM asyncevents.events")
            .fetch_one(&mut *tx)
            .await
            .unwrap();
        assert_eq!(left, 0, "the log is empty inside the transaction");

        let err = seed_mockup_on(&mut tx).await.err().expect("an empty log is refused");
        assert_eq!(
            err.to_string(),
            "eventctl: seed-mockup: the event log is empty; run demoseed first"
        );
        assert_eq!(seed_rows(&mut tx).await, 0, "a refused seed writes no seed.mockup-* row");
        tx.rollback().await.unwrap();

        // One event: the busiest stream has no event to put before the poison event.
        let one = topic("one");
        let mut tx = pool.begin().await.unwrap();
        sqlx::query("DELETE FROM asyncevents.events").execute(&mut *tx).await.unwrap();
        append(&mut tx, &one, 1).await;
        let err = seed_mockup_on(&mut tx).await.err().expect("a one-event stream is refused");
        assert_eq!(
            err.to_string(),
            format!(
                "eventctl: seed-mockup: the busiest stream {one} v1 has 1 event; \
                 the paused row needs one event before its poison event, so run demoseed first"
            )
        );
        assert_eq!(seed_rows(&mut tx).await, 0, "a refused seed writes no seed.mockup-* row");
        tx.rollback().await.unwrap();

        // Clean twin: the same shape with two events succeeds.
        let t = topic("twin");
        let mut tx = pool.begin().await.unwrap();
        sqlx::query("DELETE FROM asyncevents.events").execute(&mut *tx).await.unwrap();
        append(&mut tx, &t, 2).await;
        let seeded = seed_mockup_on(&mut tx).await.expect("a two-event log is seeded");
        assert_eq!((seeded.topic.as_str(), seeded.version, seeded.events), (t.as_str(), 1, 2));
        assert_eq!(seed_rows(&mut tx).await, 2);
        tx.rollback().await.unwrap();

        let after: i64 = sqlx::query_scalar(
            "SELECT count(*) FROM asyncevents.subscriptions WHERE subscription_id = ANY($1)",
        )
        .bind([PAUSED_ID, LAGGING_ID].map(String::from).to_vec())
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(after, 0, "all transactions rolled back");
    })
    .await;
}

/// Appends `n` events on `(topic, 1)` inside `conn`'s transaction.
async fn append(conn: &mut sqlx::PgConnection, topic: &str, n: i64) {
    sqlx::query(
        "INSERT INTO asyncevents.events \
           (generation, producer_xid, topic, contract_version, payload) \
         SELECT 0, (100 + g)::text::xid8, $1, 1, '{}'::jsonb \
         FROM generate_series(0, $2::int - 1) AS g",
    )
    .bind(topic)
    .bind(n)
    .execute(conn)
    .await
    .unwrap();
}
